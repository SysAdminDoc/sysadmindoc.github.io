// Redirects for the /projects/<Repo>/ pages removed in 864d3451, which still
// draw visits from old links (92 in the week to 2026-09-23). deploy-vps.mjs
// writes this from dist/projects.json and ships it beside the Caddyfile, which
// imports it: each repo the catalog knows goes to its GitHub page for good.
// Anything else falls through to a catalog search in the Caddyfile itself.

// Only these characters reach a Location header, and the Caddyfile's own
// matcher uses the same set.
export const SAFE_REPO_NAME = /^[A-Za-z0-9._-]+$/;

/** Caddyfile `redir` lines for every GitHub repository in a parsed projects.json. */
export function projectRedirectsCaddy(projectsJson) {
  const lines = ['# Generated by scripts/deploy-vps.mjs from dist/projects.json. Do not edit.'];
  const seen = new Set();
  for (const project of projectsJson?.projects ?? []) {
    let url;
    try {
      url = new URL(project?.urls?.repository ?? '');
    } catch {
      continue;
    }
    if (url.protocol !== 'https:' || url.hostname !== 'github.com') continue;
    const [owner, repo, ...rest] = url.pathname.split('/').filter(Boolean);
    if (!owner || !repo || rest.length || !SAFE_REPO_NAME.test(owner) || !SAFE_REPO_NAME.test(repo) || seen.has(repo)) continue;
    seen.add(repo);
    const target = `https://github.com/${owner}/${repo}`;
    lines.push(`redir /projects/${repo}/ ${target} 301`, `redir /projects/${repo} ${target} 301`);
  }
  return `${lines.join('\n')}\n`;
}
